CREATE OR REPLACE FUNCTION fn_rekap_halaman_by_juz(juz_filter integer[])
RETURNS TABLE (
	total_juz integer,
    jml_halaman integer,
    awal_halaman integer,
    akhir_halaman integer
)
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN QUERY
  WITH a AS (
    SELECT
      juz,
      COUNT(id) AS halaman_count,
      MIN(id) AS min_halaman,
      MAX(id) AS max_halaman
    FROM tahfidz_konversi tk
    WHERE juz = ANY(juz_filter)
    GROUP BY juz
  )
  SELECT
	COUNT(juz)::integer,
    SUM(halaman_count)::integer,
    MIN(min_halaman),
    MAX(max_halaman)
  FROM a;
END;
$$;



